// ─── Admin demo (dev only) ────────────────────────────────────────────────────

/**
 * GET /api/auth/admin/users-demo
 *
 * DEVELOPMENT ONLY — never deploy this without authentication.
 * Returns username, email, salt, and passwordHash for every user.
 * Demonstrates that:
 *   - No plaintext password is stored
 *   - No pepper is stored
 *   - Two users with the same password have different salts and hashes
 *
 * ❌ Never exposes the pepper
 */
export async function adminUsersDemo(
  _req: Request,
  res: Response
): Promise<void> {
  if (process.env.NODE_ENV === "production") {
    res
      .status(403)
      .json({ success: false, message: "Not available in production" });
    return;
  }

  const users = await User.find().select("+passwordHash +salt");
  const demo = users.map((u) => ({
    username: u.username,
    email: u.email,
    salt: u.salt,
    passwordHash: u.passwordHash,
    createdAt: u.createdAt,
    // ❌ pepper: never — it's not in DB
    // ❌ password: never — it's not in DB
  }));

  res.status(200).json({ success: true, users: demo });
}

// ─── Hash demo — two-case demonstration ─────────────────────────────────────

/**
 * POST /api/auth/demo/hash-cases
 *
 * DEVELOPMENT ONLY endpoint for the educational lab demo.
 *
 * Takes a submitted password + email and returns a comparison result
 * showing BOTH cases:
 *   Case A (MATCH):    submittedPassword + storedSalt + pepper → hash == storedHash ✔
 *   Case B (NO MATCH): wrongPassword    + storedSalt + pepper → hash != storedHash ✗
 *
 * Returns:
 *   - saltPrefix (first 8 chars of salt — safe to show)
 *   - hashPrefix (first 16 chars of stored hash — safe to show)
 *   - caseA: { computedHashPrefix, matched: true }
 *   - caseB: { computedHashPrefix, matched: false }
 *
 * ❌ Never returns full pepper
 * ❌ Never returns full passwordHash (only a prefix for visualization)
 */
const hashDemoSchema = z.object({
  email: z.string().email().toLowerCase().trim(),
  password: z.string().min(1),
  wrongPassword: z.string().min(1),
});

export async function hashDemoTwoCases(
  req: Request,
  res: Response,
  next: NextFunction
): Promise<void> {
  if (process.env.NODE_ENV === "production") {
    res.status(403).json({ success: false, message: "Not available in production" });
    return;
  }

  try {
    const parsed = hashDemoSchema.safeParse(req.body);
    if (!parsed.success) {
      res.status(400).json({ success: false, message: "email, password and wrongPassword are required" });
      return;
    }

    const { email, password, wrongPassword } = parsed.data;
    const pepper = process.env.PEPPER!;

    // Fetch user (need their stored salt and hash)
    const user = await User.findOne({ email }).select("+passwordHash +salt");
    if (!user) {
      res.status(404).json({ success: false, message: "User not found — register first" });
      return;
    }

    // Case A: correct password + storedSalt + pepper → should MATCH
    const hashA = await hashPassword(password, user.salt, pepper);
    const matchedA = await verifyPassword(password, user.salt, pepper, user.passwordHash);

    // Case B: wrong password + storedSalt + pepper → should NOT match
    const hashB = await hashPassword(wrongPassword, user.salt, pepper);
    const matchedB = await verifyPassword(wrongPassword, user.salt, pepper, user.passwordHash);

    res.status(200).json({
      success: true,
      username: user.username,
      // Show only safe prefixes for educational display — never the full hash or pepper
      saltPrefix: user.salt.slice(0, 8) + "…",
      storedHashPrefix: user.passwordHash.slice(0, 16) + "…",
      pepperNote: "[loaded from .env — never revealed]",
      caseA: {
        label: "Correct Password",
        passwordUsed: password,        // show what was entered
        computedHashPrefix: hashA.slice(0, 16) + "…",
        matched: matchedA,             // should be true
        verdict: matchedA ? "✅ MATCH — Login Successful" : "❌ UNEXPECTED MISMATCH",
      },
      caseB: {
        label: "Wrong Password",
        passwordUsed: wrongPassword,   // show what was entered
        computedHashPrefix: hashB.slice(0, 16) + "…",
        matched: matchedB,             // should be false
        verdict: matchedB ? "⚠ UNEXPECTED MATCH" : "❌ NO MATCH — Access Denied",
      },
    });
  } catch (err) {
    next(err);
  }
}
