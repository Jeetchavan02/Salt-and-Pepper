import { Request, Response, NextFunction } from "express";
import { z } from "zod";
import User from "../models/User";
import { generateSalt, hashPassword, verifyPassword } from "../utils/passwordHash";

// ─── Zod validation schemas ──────────────────────────────────────────────────

const registerSchema = z.object({
  username: z
    .string()
    .min(3, "Username must be at least 3 characters")
    .max(30, "Username must not exceed 30 characters")
    .trim(),
  email: z.string().email("Invalid email address").toLowerCase().trim(),
  password: z
    .string()
    .min(8, "Password must be at least 8 characters")
    .max(128, "Password too long"),
});

const loginSchema = z.object({
  email: z.string().email("Invalid email address").toLowerCase().trim(),
  password: z.string().min(1, "Password is required"),
});

// ─── Registration ─────────────────────────────────────────────────────────────

/**
 * POST /api/auth/register
 *
 * Registration flow:
 *   1. Validate input (username, email, password)
 *   2. Generate a cryptographically secure random salt — SERVER SIDE ONLY
 *      (The user NEVER provides the salt. It is generated by crypto.randomBytes.)
 *   3. Retrieve server-side pepper from process.env.PEPPER
 *   4. Combine: password + salt + pepper
 *   5. scrypt-hash the combination
 *   6. Store username, email, passwordHash, salt in MongoDB
 *   7. ❌ Never store plaintext password
 *   8. ❌ Never store pepper
 */
export async function register(
  req: Request,
  res: Response,
  next: NextFunction
): Promise<void> {
  try {
    // 1. Validate and sanitise
    const parsed = registerSchema.safeParse(req.body);
    if (!parsed.success) {
      res.status(400).json({
        success: false,
        message: parsed.error.errors.map((e) => e.message).join(", "),
      });
      return;
    }

    const { username, email, password } = parsed.data;

    // 2. Generate unique salt for this user — NEVER taken from user input
    //    crypto.randomBytes(16) → 32-char hex string
    const salt = generateSalt();

    // 3. Retrieve pepper — must come from environment, never the client
    const pepper = process.env.PEPPER!;

    // 4 + 5. Hash: password + salt + pepper → scrypt → hex string
    const passwordHash = await hashPassword(password, salt, pepper);

    // 6. Persist only: username, email, passwordHash, salt
    const user = await User.create({ username, email, passwordHash, salt });

    // Development-only debug log — NEVER logs plaintext password or pepper value
    if (process.env.NODE_ENV !== "production") {
      console.log("📝  [REGISTER DEBUG]");
      console.log("    Salt generated (server-side) : YES ✔");
      console.log("    Pepper loaded from .env      : YES ✔");
      console.log("    Password hashed (scrypt)     : YES ✔");
      console.log("    Stored hash                  : YES ✔");
      console.log(`    Username                     : ${user.username}`);
      console.log(`    Email                        : ${user.email}`);
    }

    res.status(201).json({
      success: true,
      message: "User registered successfully",
    });
  } catch (err: unknown) {
    // Handle MongoDB duplicate key errors
    if (
      err instanceof Error &&
      (err as NodeJS.ErrnoException & { code?: number }).code === 11000
    ) {
      const keyErr = err as { keyValue?: Record<string, unknown> };
      const field = keyErr.keyValue
        ? Object.keys(keyErr.keyValue)[0]
        : "field";
      res.status(409).json({
        success: false,
        message: `An account with that ${field} already exists`,
      });
      return;
    }
    next(err);
  }
}

// ─── Login ────────────────────────────────────────────────────────────────────

/**
 * POST /api/auth/login
 *
 * Login flow:
 *   1. Validate input
 *   2. Find user by email
 *   3. Fetch stored passwordHash and salt from MongoDB — explicit .select()
 *   4. Retrieve server-side pepper from process.env.PEPPER
 *   5. Reconstruct: submittedPassword + storedSalt + pepper
 *   6. scrypt-hash the reconstruction
 *   7. Compare generated hash vs storedHash (timing-safe)
 *   8. Respond success or failure — do NOT reveal which field was wrong
 *
 * ❌ Do NOT generate a new salt during login — use the stored one
 * ❌ Do NOT send passwordHash or salt in the response
 */
export async function login(
  req: Request,
  res: Response,
  next: NextFunction
): Promise<void> {
  try {
    // 1. Validate
    const parsed = loginSchema.safeParse(req.body);
    if (!parsed.success) {
      res.status(400).json({
        success: false,
        message: parsed.error.errors.map((e) => e.message).join(", "),
      });
      return;
    }

    const { email, password } = parsed.data;

    // 2 + 3. Find user; explicitly select passwordHash and salt
    //        (they are select:false by default to prevent accidental exposure)
    const user = await User.findOne({ email }).select("+passwordHash +salt");

    // Use a vague message to avoid account enumeration
    const INVALID_MSG = "Invalid credentials";

    if (!user) {
      res.status(401).json({ success: false, message: INVALID_MSG });
      return;
    }

    // 4. Pepper is on the server only — never in DB, never sent to client
    const pepper = process.env.PEPPER!;

    // 5 + 6 + 7. Recompute hash and compare
    //   submittedPassword + storedSalt (NOT a new salt) + pepper → scrypt → compare
    const isMatch = await verifyPassword(
      password,
      user.salt,        // storedSalt fetched from MongoDB — never regenerated
      pepper,
      user.passwordHash // storedHash fetched from MongoDB
    );

    if (!isMatch) {
      res.status(401).json({ success: false, message: INVALID_MSG });
      return;
    }

    // 8. Success — return only non-sensitive info
    res.status(200).json({
      success: true,
      message: "Login successful",
      user: {
        id: user._id,
        username: user.username,
        email: user.email,
      },
    });
  } catch (err) {
    next(err);
  }
}

